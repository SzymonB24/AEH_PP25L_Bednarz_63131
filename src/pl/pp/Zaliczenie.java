package pl.pp;

public class Zaliczenie {
    public static void main(String[] args) {

        //stworzenie zmiennej x o wartosci 10
        int x = 10;
        System.out.println("x = " + x);

        //obliczenie dwukrotnosci x
        var result = x * 2;
        System.out.println("x * 2 = " + result);

        //obliczenie x^2
        result = x * x;
        System.out.println("x^2 = " + result);

    }
}

